function ymdNum(t) { return t.y * 10000 + t.m * 100 + t.d; }
function parseYmd(s) { const [y, m, d] = s.split("-").map(Number); return { y, m, d }; }
function addDaysYmd(t, n) {
  const x = new Date(Date.UTC(t.y, t.m - 1, t.d + n));
  return { y: x.getUTCFullYear(), m: x.getUTCMonth() + 1, d: x.getUTCDate(), wd: x.getUTCDay() };
}

