function birthPillar(birth) {
  const hour = birthHour(birth.time);
  const bi = ganzhiIndex(birth.y, birth.m, birth.d) + (hour && hour.nextDay ? 1 : 0);
  return ganzhiName(bi % 60);
}

function monthScore(me, mp, seed) {
  const g = MONTH_GODS[tenGod(me.stem, mp.stem)];
  const mod = BRANCH_MOD[ttiRelation(me.branch, mp.branch)];
  return g.scores.map((s, k) => clampScore(s + mod.delta + (((seed + k * 5) % 7) - 3)));
}
function avg(a) { return Math.round(a.reduce((x, y) => x + y, 0) / a.length); }

// 이번 달(절월) 운세. offset 0 = 이번 달, 1 = 다음 달
function monthResult(birth, today, offset) {
  const i = monthIndexOf(today) + (offset || 0);
  if (i < 0 || i >= JIE.length - 1) return null;
  const me = birthPillar(birth);
  const mp = monthAt(i);
  const god = tenGod(me.stem, mp.stem);
  const g = MONTH_GODS[god];
  const mod = BRANCH_MOD[ttiRelation(me.branch, mp.branch)];
  const scores = monthScore(me, mp, i * 11 + me.stem * 3);
  // 행운의 날: 남은 기간(오늘 이후) 중 하루 운세 평균 점수가 높은 3일
  const from = ymdNum(mp.start) > ymdNum(today) ? mp.start : today;
  const days = [];
  for (let t = { ...from }; ymdNum(t) <= ymdNum(mp.end); t = addDaysYmd(t, 1)) {
    const r = sajuResult(birth, t);
    days.push({ t: addDaysYmd(t, 0), score: avg(r.scores), title: r.title, gz: r.td });
  }
  const lucky = days.slice().sort((a, b) => b.score - a.score || ymdNum(a.t) - ymdNum(b.t)).slice(0, 3)
    .sort((a, b) => ymdNum(a.t) - ymdNum(b.t));
  return {
    kind: "month", me, mp, god, title: g.title,
    total: [g.total, mod.text.replace("오늘 일진이", "이달의 기운이").replace("날이에요", "달이에요").replace("하루", "한 달")].filter(Boolean).join(" "),
    scores, love: g.love, money: g.money, work: g.work, word: g.word, action: g.action, lucky,
  };
}

// 신년운세 (Y = 입춘~다음 입춘 전까지의 해)
function yearResult(birth, Y) {
  const me = birthPillar(birth);
  const yp = yearPillar(Y);
  const god = tenGod(me.stem, yp.stem);
  const g = YEAR_GODS[god];
  const rel = ttiRelation(me.branch, yp.branch);
  const mod = BRANCH_MOD[rel];
  const scores = g.scores.map((s, k) => clampScore(s + mod.delta + (((Y * 3 + me.stem + k * 5) % 7) - 3)));
  const relText = {
    yukhap: `${Y}년의 기운이 내 일지와 육합을 이뤄 사람 복이 더해지는 해예요.`,
    samhap: `${Y}년의 기운이 내 일지와 삼합으로 통해 하는 일에 힘이 실려요.`,
    same: `${Y}년의 기운이 내 일지와 같아 익숙한 흐름 속에서 실력을 다지기 좋아요.`,
    chung: `${Y}년의 기운이 내 일지와 충을 이뤄 이사, 이직처럼 변화가 생기기 쉬운 해예요. 변화를 기회로 삼으면 오히려 크게 도약해요.`,
    wonjin: `사소한 오해가 쌓이기 쉬운 해예요. 서운한 건 그때그때 부드럽게 풀면 관계가 더 단단해져요.`,
    normal: "",
  }[rel];
  // 월별 흐름: 그해 입춘(인월)부터 소한(축월)까지 12개월
  const first = JIE.findIndex(([d, n]) => n === "입춘" && parseYmd(d).y === Y);
  const months = [];
  if (first >= 0) {
    for (let k = 0; k < 12 && first + k < JIE.length - 1; k++) {
      const mp = monthAt(first + k);
      months.push({ mp, score: avg(monthScore(me, mp, (first + k) * 11 + me.stem * 3)), god: tenGod(me.stem, mp.stem) });
    }
  }
  return {
    kind: "year", me, yp, god, title: g.title, total: [g.total, relText].filter(Boolean).join(" "),
    scores, love: g.love, money: g.money, work: g.work, keyword: g.keyword, months,
  };
}

// 지금 볼 신년운세 연도: 11월~입춘 전에는 다가오는 해, 입춘 이후에는 올해
function fortuneYear(today) {
  const ip = JIE.find(([d, n]) => n === "입춘" && parseYmd(d).y === today.y);
  const beforeIpchun = today.m <= 2 && (!ip || ymdNum(today) < ymdNum(parseYmd(ip[0])));
  const Y = beforeIpchun ? today.y : today.m >= 11 ? today.y + 1 : today.y;
  return JIE.some(([d, n]) => n === "입춘" && parseYmd(d).y === Y) ? Y : null;
}
