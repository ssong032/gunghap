function monthAt(i) {
  const [date, name] = JIE[i];
  const start = parseYmd(date);
  const k = JIE_NAMES.indexOf(name);
  const sajuYear = name === "소한" ? start.y - 1 : start.y; // 소한(1월)은 아직 전년도
  const ys = yearPillar(sajuYear).stem;
  const stem = (((ys % 5) * 2 + 2) + k) % 10;
  const branch = (2 + k) % 12;
  const end = i + 1 < JIE.length ? addDaysYmd(parseYmd(JIE[i + 1][0]), -1) : null;
  return { stem, branch, ko: STEMS[stem] + BRANCHES[branch], hj: STEMS_HJ[stem] + BRANCHES_HJ[branch], jie: name, start, end, sajuYear };
}
function monthIndexOf(t) {
  const n = ymdNum(t);
  let idx = -1;
  JIE.forEach(([d], i) => { if (ymdNum(parseYmd(d)) <= n) idx = i; });
  return idx; // -1이면 표 범위 밖
}

