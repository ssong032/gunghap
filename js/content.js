// 재성(바쁘게 다스림) → 비겁 오행으로 힘 보태기 / 관성(압박) → 인성 오행으로 바꾸기 / 인성(받기만 함) → 식상 오행으로 움직이기
function helperElement(myStem, god) {
  const e = Math.floor(myStem / 2);
  const shift = { 비견: 1, 겁재: 1, 식신: 4, 상관: 4, 편재: 0, 정재: 0, 편관: 4, 정관: 4, 편인: 1, 정인: 1 }[god];
  return (e + shift) % 5;
}

